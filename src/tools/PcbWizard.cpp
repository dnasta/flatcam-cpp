std::vector<std::string> pcbWizardReadLines(const std::string& path, bool* ok) {
    std::ifstream f(path, std::ios::binary);
    if (ok) *ok = static_cast<bool>(f);
    std::vector<std::string> out;
    if (!f) return out;
    std::string cur;
    char c;
    while (f.get(c)) {
        if (c == '\r') {
            if (f.peek() == '\n') f.get();
            c = '\n';
        }
        cur += c;
        if (c == '\n') {
            out.push_back(cur);
            cur.clear();
        }
    }
    if (!cur.empty()) out.push_back(cur);
    return out;
}

bool pcbWizardReadInf(const std::vector<std::string>& lines, PcbWizardInf& r) {
    static const std::regex toolRe(R"(^T(\d+)\s+(\d*\.?\d+)$)");
    static const std::regex formatRe(R"(^(\d+)\.?(\d+)\s*format,\s*(inches|metric)?,\s*(absolute|incremental)?.*$)");
    for (const std::string& raw : lines) {
        const std::string l = strip(raw);
        std::smatch m;
        if (std::regex_search(l, m, toolRe)) {
            const int t = std::stoi(m[1]);
            const double d = std::stod(m[2]);
            bool found = false;
            for (auto& [k, v] : r.tools)
                if (k == t) {
                    v = d;
                    found = true;
                }
            if (!found) r.tools.push_back({t, d});
            continue;
        }
        if (std::regex_search(l, m, formatRe)) {
            r.integral = std::stoi(m[1]);
            r.fractional = std::stoi(m[2]);
            r.units = m[3] == "inches" ? "INCH" : "METRIC";
        }
    }
    return !r.tools.empty();
}

std::string pcbWizardMerge(const std::vector<std::string>& excLines, const PcbWizardInf& inf, int integral,
                           int fractional, const std::string& units, const std::string& zeros,
                           const std::string& version, const std::string& versionDate, const std::string& timeStr) {
    std::string out;
    for (const std::string& line : excLines) {
        out += line;
        if (line.find("M48") == std::string::npos) continue;
        out += ";EXCELLON RE-GENERATED BY FLATCAM v" + version + " - www.flatcam.org - Version Date: " + versionDate + "\n";
        out += ";Created on : " + timeStr + "\n";
        out += ";FILE_FORMAT=" + std::to_string(integral) + ":" + std::to_string(fractional) + "\n";
        out += units + "," + zeros + "\n";
        for (const auto& [t, d] : inf.tools) out += "T" + std::to_string(t) + "C" + pyFloatRepr(d) + "\n";
    }
    return out;
}

