CncJob::CncJob(DrillJobSettings settings) : settings_(std::move(settings)) {}

std::string CncJob::gcodeHeader(const GcodeHeaderInfo& info) {
    std::string g;
    g += "(G-CODE GENERATED BY FLATCAM v" + info.version + " - www.flatcam.org - Version Date: " + info.versionDate + ")\n\n";
    g += "(Name: " + info.name + ")\n";
    g += "(Type: G-code from " + info.type + ")\n";
    g += "(Units: " + info.units + ")\n\n";
    g += "(Created on " + info.createdOn + ")\n\n";
    return g;
}

std::string CncJob::exportGcode(const GcodeHeaderInfo& info) const {
    return gcodeHeader(info) + startGcode_ + "\n" + gcode_ + "\n";
}

bool CncJob::generateFromExcellon(const Excellon& excellon) {
    lastError_.clear();
    startGcode_.clear();
    gcode_.clear();
    toolGcodes_.clear();

    const auto pp = makePreprocessor(settings_.preprocessor);
    if (!pp) {
        lastError_ = "Postprocesador desconocido: " + settings_.preprocessor;
        return false;
    }

    // Herramientas con agujeros, en orden numérico.
    std::vector<int> selected;
    for (const auto& [id, tool] : excellon.drillTools()) {
        if (!tool.drills.empty() && settings_.tools.count(id)) selected.push_back(id);
    }
    if (selected.empty()) {
        lastError_ = "El Excellon no tiene agujeros para las herramientas configuradas";
        return false;
    }
    for (const auto& [id, tool] : excellon.drillTools()) {
        if (!tool.slots.empty() && settings_.tools.count(id)) {
            // El generador de taladrado del original solo recorre agujeros; las ranuras se fresan con otra herramienta.
            Logger::warning("CncJob: la herramienta T" + std::to_string(id) + " tiene " + std::to_string(tool.slots.size()) +
                            " ranura(s) que no se incluyen en el G-code de taladrado");
        }
    }

    std::array<double, 2> firstPoint{0.0, 0.0};
    if (const auto& tc = settings_.tools.at(selected.front()).toolchangeXY) firstPoint = *tc;

    for (std::size_t k = 0; k < selected.size(); ++k) {
        const int tool = selected[k];
        std::string tGcode, startGcode;
        const bool isFirst = (k == 0), isLast = (k + 1 == selected.size());
        if (!toolGcode(tool, excellon.drillTools().at(tool).drills, excellon, firstPoint, isFirst, isLast, tGcode, startGcode)) {
            return false;
        }
        if (!startGcode.empty()) startGcode_ = startGcode;
        gcode_ += tGcode;
        toolGcodes_.push_back(tGcode);
    }
    return true;
}

bool CncJob::toolGcode(int tool, const std::vector<Point2D>& points, const Excellon& ex,
                       std::array<double, 2>& firstPoint, bool isFirst, bool isLast, std::string& tGcode,
                       std::string& startGcode) {
    const DrillToolSettings& ts = settings_.tools.at(tool);
    const auto pp = makePreprocessor(settings_.preprocessor);
    if (points.empty()) {
        lastError_ = "La herramienta " + std::to_string(tool) + " no tiene agujeros";
        return false;
    }
    if (ts.cutZ.value() == 0.0) {
        lastError_ = "La Z de corte de la herramienta " + std::to_string(tool) + " es cero: no habría corte";
        return false;
    }

    // ---- parámetros comunes del postprocesador
    PreprocessorParams p;
    p.units = settings_.units;
    p.coordsDecimals = settings_.coordsDecimals;
    p.decimals = settings_.decimals;
    p.frDecimals = settings_.frDecimals;
    p.feedrate = ts.feedrateZ;
    p.zFeedrate = ts.feedrateZ;
    p.feedrateRapid = ts.feedrateRapid;
    p.zCut = ts.cutZ;
    p.multidepth = ts.multidepth;
    p.zDepthPerCut = ts.depthPerPass;
    p.zMove = ts.travelZ;
    p.useUi = true;
    p.toolchange = true;
    p.zToolchange = ts.toolchangeZ;
    p.xyToolchange = toPyPair(ts.toolchangeXY);
    p.startZ = ts.startZ;
    p.zEnd = ts.endZ;
    p.xyEnd = toPyPair(ts.endXY);
    p.stepsPerCircle = settings_.stepsPerCircle;
    p.ppExcellonName = settings_.preprocessor;
    p.spindleSpeed = ts.spindleSpeed;
    p.spindleDir = ts.spindleDir;
    p.dwellTime = ts.dwellTime;
    p.tool = tool;
    p.toolC = PyNumber(ex.drillTools().at(tool).tooldia);
    p.fPlunge = ts.fPlunge;

    const auto b = boundsOf(ex.solidGeometry());
    if (b) {
        p.options.xmin = PyNumber(b->xmin);
        p.options.ymin = PyNumber(b->ymin);
        p.options.xmax = PyNumber(b->xmax);
        p.options.ymax = PyNumber(b->ymax);
    }
    p.options.type = "Excellon";
    for (const auto& [id, t] : ex.drillTools()) {
        if (!settings_.tools.count(id)) continue;
        const DrillToolSettings& s = settings_.tools.at(id);
        if (!t.drills.empty()) {
            p.options.toolsInUse.push_back(ToolInUse{id, PyNumber(t.tooldia), static_cast<int>(t.drills.size()),
                                                     static_cast<int>(t.slots.size())});
        }
        p.excTools.push_back(ExcToolInfo{id, PyNumber(t.tooldia), s.feedrateZ, s.feedrateRapid, s.cutZ, s.offsetZ,
                                         s.depthPerPass, s.travelZ});
        if (!t.drills.empty()) {
            ExcToolInfo cnc;
            cnc.tool = id;
            cnc.offsetZ = s.offsetZ;
            p.excCncTools.push_back(cnc);
        }
    }

    // ---- orden de los agujeros
    std::vector<Point2D> ordered;
    if (settings_.order == DrillOrder::Optimized) {
        for (std::size_t i : PathOptimizer::order(points, {firstPoint[0], firstPoint[1]})) ordered.push_back(points[i]);
    } else {
        ordered = points;
    }

    // ---- G-code
    if (isFirst) startGcode = pp->startCode(p) + "\n";
    tGcode += pp->zFeedrateCode(p) + "\n";
    tGcode += pp->toolchangeCode(p) + "\n";
    tGcode += pp->zFeedrateCode(p) + "\n";
    tGcode += pp->spindleCode(p) + "\n";
    if (ts.dwell) tGcode += pp->dwellCode(p) + "\n";

    const double oldZcut = ts.cutZ.value();
    const double zOffset = ts.offsetZ.value() * (-1);
    double zCut = zOffset + oldZcut;
    p.zCut = PyNumber(zCut);

    Point2D last = ordered.front();
    for (const Point2D& pt : ordered) {
        p.x = pt.x;
        p.y = pt.y;
        last = pt;
        tGcode += pp->rapidCode(p) + "\n";  // sin áreas de exclusión el viaje es un solo movimiento rápido

        if (ts.multidepth && std::fabs(zCut) > std::fabs(ts.depthPerPass.value())) {
            const double doc = zCut;
            double z = 0.0;
            while (std::fabs(z) < std::fabs(doc)) {
                z -= ts.depthPerPass.value();
                if (std::fabs(doc) < std::fabs(z) && std::fabs(z) < std::fabs(doc) + ts.depthPerPass.value()) z = doc;
                p.zCut = PyNumber(z);
                tGcode += pp->downCode(p) + "\n";
                if (!ts.fRetract) tGcode += pp->upToZeroCode(p) + "\n";
                tGcode += pp->liftCode(p) + "\n";
            }
            zCut = z;
        } else {
            p.zCut = PyNumber(zCut);
            tGcode += pp->downCode(p) + "\n";
            if (!ts.fRetract) tGcode += pp->upToZeroCode(p) + "\n";
            tGcode += pp->liftCode(p) + "\n";
        }
    }

    if (isLast) {
        tGcode += pp->spindleStopCode(p) + "\n";
        p.x = 0;
        p.y = 0;
        tGcode += pp->endCode(p) + "\n";
    }
    firstPoint = {last.x, last.y};
    return true;
}

