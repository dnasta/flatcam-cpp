/// Límites de una lista de figuras, ignorando las vacías.
std::optional<BoundingBox> boundsOf(const ShapeList& list) {
    std::optional<BoundingBox> acc;
    for (const Shape& s : list) {
        const auto b = s.bounds();
        if (!b) continue;
        acc = acc ? acc->merged(*b) : *b;
    }
    return acc;
}

std::optional<std::array<PyNumber, 2>> toPyPair(const std::optional<std::array<double, 2>>& v) {
    if (!v) return std::nullopt;
    return std::array<PyNumber, 2>{PyNumber((*v)[0]), PyNumber((*v)[1])};
}

