double decFormat(double v, int dec) {
    char buf[64];
    std::snprintf(buf, sizeof buf, "%.*f", dec, v);
    return std::strtod(buf, nullptr);
}

std::vector<Point2D> autolevelGrid(const BoundingBox& b, int rows, int cols, int decimals) {
    const double width = std::abs(b.xmax - b.xmin), height = std::abs(b.ymax - b.ymin);
    const double dx = cols == 1 ? 0 : width / (cols - 1);
    const double dy = rows == 1 ? 0 : height / (rows - 1);
    std::vector<Point2D> out;
    double y = b.ymin;
    for (int r = 0; r < rows; ++r) {
        double x = b.xmin;
        for (int c = 0; c < cols; ++c) {
            out.push_back({decFormat(x, decimals), decFormat(y, decimals)});
            x += dx;
        }
        y += dy;
    }
    return out;
}

bool autolevelVoronoi(std::vector<ProbePoint>& points, const BoundingBox& b, bool mm) {
    const Shape env = Shape::polygon({{b.xmin, b.ymin}, {b.xmax, b.ymin}, {b.xmax, b.ymax}, {b.xmin, b.ymax}})
                          .envelope()
                          .buffer(mm ? 1.0 : 0.039);
    ShapeList pts;
    for (const ProbePoint& p : points) pts.push_back(Shape::point(p.point));
    Shape diagram;
    try {
        diagram = Shape::collection(pts).voronoiDiagram(env);
    } catch (const GeometryError&) {
        return false;  // el original corre los puntos al azar 1e-9 y lo vuelve a intentar
    }
    ShapeList cells;
    for (const Shape& c : diagram.parts()) cells.push_back(c.intersection(env));
    for (ProbePoint& p : points) {
        const Shape sp = Shape::point(p.point);
        for (const Shape& c : cells)
            if (sp.within(c)) p.cell = c;  // la última celda que lo contiene
    }
    return true;
}

std::string autolevelProbingGcode(const std::vector<Point2D>& points, const ProbingGcodeParams& p) {
    std::string probing, openfile, closefile;
    if (p.controller == "MACH3" || p.controller == "MACH4") {
        probing = "G31";
        openfile = "M40";
        closefile = "M41";
    } else if (p.controller == "LinuxCNC") {
        probing = "G38.2";
        openfile = "(PROBEOPEN a_probing_points_file.txt)";
        closefile = "(PROBECLOSE)";
    } else {
        return std::string();  // GRBL (otro camino) o un controlador desconocido
    }
    std::string header = "(G-CODE GENERATED BY FLATCAM v" + p.version + " - www.flatcam.org - Version Date: " +
                         p.versionDate + ")\n\n";
    header += "(This is a autolevelling probing GCode.)\n(Make sure that before you start the job you first do a zero "
              "for all axis.)\n\n";
    header += "(Name: " + p.name + ")\n";
    header += "(Type: Autolevelling Probing GCode )\n";
    header += "(Units: " + p.units + ")\n";
    header += "(Created on " + p.timeStr + ")\n";
    std::string g = header + "\n";
    if (p.controller == "LinuxCNC")
        g += "The file with the stored probing points can be found\nin the configuration folder for LinuxCNC.\n"
             "The name of the file is: a_probing_points_file.txt.\n";
    g += p.units == "MM" ? "G21\n" : "G20\n";
    g += "G90\n";
    g += openfile + "\n";
    const std::string travel = pyFloatRepr(decFormat(p.travelZ, p.coordsDecimals));
    g += "G0 Z" + travel + "\n";
    for (const Point2D& pt : points) {
        const double x = decFormat(pt.x, p.decimals), y = decFormat(pt.y, p.decimals);
        g += "G0 X" + pyFloatRepr(decFormat(x, p.coordsDecimals)) + "Y" + pyFloatRepr(decFormat(y, p.coordsDecimals)) + "\n";
        g += probing + " Z" + pyFloatRepr(decFormat(p.probeDepth, p.coordsDecimals)) + " F" +
             pyFloatRepr(decFormat(p.probeFeedrate, p.frDecimals)) + "\n";
        g += "G0 Z" + travel + "\n";
    }
    g += closefile + "\n";
    g += "M2";
    return g;
}

bool autolevelImportHeightMap(const std::vector<std::string>& lines, std::vector<ProbePoint>& points) {
    std::size_t idx = 0;
    for (std::string line : lines) {
        if (line.empty()) continue;
        ++idx;
        // line.replace(' ', ',').replace('\n', '').split(',')
        std::vector<std::string> f{""};
        for (char c : line) {
            if (c == '\n') continue;
            if (c == ' ' || c == ',') f.push_back("");
            else f.back() += c;
        }
        auto num = [](const std::string& s, double& out) {
            if (s.empty()) return false;
            char* e;
            out = std::strtod(s.c_str(), &e);
            return *e == '\0' || *e == '\r';
        };
        double z;
        if (f.size() < 3 || !num(f[2], z)) return false;
        if (points.size() < idx) {
            double x, y;
            if (!num(f[0], x) || !num(f[1], y)) return false;
            points.resize(idx);
            points[idx - 1].point = {x, y};
        }
        points[idx - 1].height = z;
    }
    return true;
}

std::vector<std::string> grblJogCommands(const std::string& direction, double step, double feedrate,
                                         const std::string& units, double travelZ) {
    const std::string g = units == "IN" ? "G20" : "G21";
    const std::string st = "(" + pyFloatRepr(step) + ",)";
    const std::string fr = pyFloatRepr(feedrate);
    if (direction == "xplus") return {"$J=G91 " + g + " X" + st + " F" + fr};
    if (direction == "xminus") return {"$J=G91 " + g + " X-" + st + " F" + fr};
    if (direction == "yplus") return {"$J=G91 " + g + " Y" + st + " F" + fr};
    if (direction == "yminus") return {"$J=G91 " + g + " Y-" + st + " F" + fr};
    if (direction == "zplus") return {"$J=G91 " + g + " Z" + st + " F" + fr};
    if (direction == "zminus") return {"$J=G91 " + g + " Z-" + st + " F" + fr};
    if (direction == "origin")
        return {"$J=G90 " + g + " Z" + pyFloatRepr(travelZ) + " F" + fr, "$J=G90 " + g + " X0.0 Y0.0 F" + fr};
    return {};
}

