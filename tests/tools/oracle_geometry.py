#!/usr/bin/env python3
"""Oráculo del G-code de geometría: ejecuta `CNCjob.geometry_tool_gcode_gen` ORIGINAL (FlatCAM 2024.4).

Toma el recorrido del contorno de `tests/data/DosCau_PPal-Edge_Cuts.nc` como línea de entrada (así el resultado se
puede comparar con ese mismo archivo) y los parámetros de corte guardados en el proyecto del usuario
(`tests/data/dosificador_PCB_principal.params.json`). Escribe `tests/golden_geometry.h` con el G-code generado y la
función que arma los mismos parámetros en C++.

Requisitos (solo para regenerar el archivo): python3 -m pip install shapely numpy
Uso:  python3 tests/tools/oracle_geometry.py
"""
import json
import os
import re
import sys

from shapely.geometry import LineString

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from oracle_common import DATA, REF, ROOT, FakeApp, install_stubs, load  # noqa: E402

OUT = os.path.join(ROOT, "tests", "golden_geometry.h")


class ExcAreas:
    exclusion_areas_storage = []

    @staticmethod
    def travel_coordinates(start_point, end_point, tooldia):
        return [(None, end_point)]


def num(v):
    return repr(float(v))


def cs(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def read_real_nc():
    lines = open(os.path.join(DATA, "DosCau_PPal-Edge_Cuts.nc"), newline="").read().replace("\r", "").split("\n")
    header = {}
    for l in lines[:12]:
        m = re.match(r"\(G-CODE GENERATED BY FLATCAM v(\S+) - www.flatcam.org - Version Date: (\S+)\)", l)
        if m:
            header["version"], header["date"] = m.group(1), m.group(2)
        for key in ("Name", "Type", "Units", "Created on"):
            if l.startswith("(%s" % key):
                header[key] = l[len(key) + 3:-1] if key != "Created on" else l[len("(Created on "):-1]
    # Cada trazado empieza en un `G00 X.. Y..` seguido de `G01 F..` y `G01 Z-..` y sigue con los `G01 X.. Y..`.
    paths = []
    for k, l in enumerate(lines):
        m = re.match(r"^G00 X(-?[\d.]+) Y(-?[\d.]+)$", l)
        if m and k + 2 < len(lines) and lines[k + 2].startswith("G01 Z-"):
            paths.append([(float(m.group(1)), float(m.group(2)))])
        elif paths and re.match(r"^G01 X", l):
            m1 = re.match(r"^G01 X(-?[\d.]+) Y(-?[\d.]+)$", l)
            paths[-1].append((float(m1.group(1)), float(m1.group(2))))
    return header, paths


def main():
    install_stubs()
    sys.path.insert(0, REF)
    camlib = load("camlib", os.path.join(REF, "camlib.py"))
    import appPreProcessor  # noqa: E402
    default_mod = load("pp_default", os.path.join(REF, "preprocessors", "default.py"))
    laser_mod = load("pp_laser", os.path.join(REF, "preprocessors", "GRBL_laser.py"))
    import math
    default_mod.math = math

    app = FakeApp()
    app.defaults.update({"cncjob_steps_per_circle": 64, "cncjob_coords_type": "G90", "geometry_f_plunge": False})
    app.preprocessors = appPreProcessor.preprocessors
    app.exc_areas = ExcAreas()
    app.dec_format = lambda v, dec=4: float("%.*f" % (dec, v))
    camlib.Geometry.app = app
    camlib.CNCjob.app = app

    header, paths = read_real_nc()
    lines = [LineString(c) for c in paths]
    proj = json.load(open(os.path.join(DATA, "dosificador_PCB_principal.params.json")))
    geo_obj = [o for o in proj["objs"] if o.get("options", {}).get("name") == "PCB ppal-Edge_Cuts.gm1_cutout"][0]
    tool = geo_obj["tools"]["1"]
    data = dict(tool["data"])
    data["optimization_type"] = "T"

    job = camlib.CNCjob(units="MM", kind="geometry", steps_per_circle=64, pp_geometry_name="default")
    job.machinist_setting = 0
    job.coords_decimals = 4
    job.fr_decimals = 2
    job.oldx = 0.0
    job.oldy = 0.0
    from shapely.ops import unary_union
    xmin, ymin, xmax, ymax = unary_union(lines).bounds
    job.options = {"name": header["Name"], "type": "Geometry", "tool_dia": tool["tooldia"], "xmin": xmin,
                   "ymin": ymin, "xmax": xmax, "ymax": ymax}
    # Rama 'T' con un optimizador que deja el orden tal cual (la rama "sin optimizar" del original está rota).
    job.optimized_travelling_salesman = lambda points, start=None: list(points)
    tools = {1: {"tooldia": tool["tooldia"], "offset": tool["offset"], "offset_value": tool["offset_value"],
                 "solid_geometry": lines, "data": data}}
    gcode, start = job.geometry_tool_gcode_gen(1, tools, first_pt=(0.0, 0.0), tolerance=0, is_first=True,
                                               is_last=True, toolchange=True)
    hdr = ("(G-CODE GENERATED BY FLATCAM v%s - www.flatcam.org - Version Date: %s)\n\n(Name: %s)\n"
           "(Type: G-code from %s)\n(Units: %s)\n\n(Created on %s)\n\n") % (
        header["version"], header["date"], header["Name"], header["Type"].replace("G-code from ", ""),
        header["Units"], header["Created on"])
    full = hdr + start + "\n" + gcode + "\n"

    def pair(v):
        return "std::array<double, 2>{%s, %s}" % (num(v[0]), num(v[1])) if v else None

    out = ["// ARCHIVO GENERADO por tests/tools/oracle_geometry.py - no editar a mano.",
           "// Referencia: CNCjob.geometry_tool_gcode_gen original (FlatCAM 2024.4) con el contorno del usuario.",
           "#pragma once", "#include <array>", "#include <string>", "#include <vector>", '#include "cam/CncJob.h"',
           "namespace golden_geometry {",
           "inline const std::vector<std::vector<flatcam::Point2D>> kPaths = {%s};" % ", ".join(
               "{" + ", ".join("{%s, %s}" % (num(x), num(y)) for x, y in c) + "}" for c in paths),
           "inline flatcam::GeometryJobSettings settings() {", "    flatcam::GeometryJobSettings s;",
           '    s.units = "MM";', "    s.order = flatcam::DrillOrder::FileOrder;", "    s.tool = 1;",
           "    flatcam::GeometryToolSettings& t = s.toolSettings;", "    t.toolDia = %s;" % num(tool["tooldia"]),
           '    t.offsetKind = "%s";' % tool["offset"], "    t.offsetValue = %s;" % num(tool["offset_value"])]
    for key, cpp in [("cutz", "cutZ"), ("depthperpass", "depthPerPass"), ("travelz", "travelZ"), ("feedrate", "feedrate"),
                     ("feedrate_z", "feedrateZ"), ("feedrate_rapid", "feedrateRapid"), ("spindlespeed", "spindleSpeed"),
                     ("dwelltime", "dwellTime"), ("endz", "endZ"), ("toolchangez", "toolchangeZ")]:
        out.append("    t.%s = %s;" % (cpp, num(data[key])))
    out.append('    t.spindleDir = "%s";' % data["spindledir"])
    for key, cpp in [("multidepth", "multidepth"), ("dwell", "dwell"), ("extracut", "extracut")]:
        out.append("    t.%s = %s;" % (cpp, str(bool(data[key])).lower()))
    if data["startz"]:
        out.append("    t.startZ = %s;" % num(data["startz"]))
    if data["endxy"]:
        out.append("    t.endXY = %s;" % pair(data["endxy"]))
    if data["toolchangexy"]:
        out.append("    t.toolchangeXY = %s;" % pair(data["toolchangexy"]))
    out += ["    return s;", "}", "inline flatcam::GcodeHeaderInfo header() {", "    flatcam::GcodeHeaderInfo h;",
            "    h.version = %s;" % cs(header["version"]), "    h.versionDate = %s;" % cs(header["date"]),
            "    h.name = %s;" % cs(header["Name"]), "    h.type = %s;" % cs(header["Type"].replace("G-code from ", "")),
            "    h.units = %s;" % cs(header["Units"]), "    h.createdOn = %s;" % cs(header["Created on"]),
            "    return h;", "}",
            "inline const std::string kStartGcode = %s;" % cs(start),
            "inline const std::string kToolGcode = %s;" % cs(gcode),
            "inline const std::string kFullFile = %s;" % cs(full), "}  // namespace golden_geometry"]
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print("Escrito", OUT, "(%d trazados, %d líneas de G-code)" % (len(paths), full.count("\n")))


if __name__ == "__main__":
    main()
